-- NUCLEO schema: execute no SQL Editor do Supabase.
-- Todas as PK são INTEGER identity. A autenticação é própria (não usa Supabase Auth).
create table if not exists public.contas (
 id integer generated by default as identity primary key,
 full_name text not null,
 username text not null unique,
 password_hash text not null,
 role text not null check (role in ('gerente','funcionario')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.empresas (
 id integer generated by default as identity primary key,
 nome text not null, logo text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.empresa_gerentes (
 id integer generated by default as identity primary key,
 empresa_id integer not null references public.empresas(id), gerente_id integer not null references public.contas(id), created_at timestamptz not null default now(), unique(empresa_id,gerente_id)
);
create table if not exists public.empresa_funcionarios (
 id integer generated by default as identity primary key,
 empresa_id integer not null references public.empresas(id), funcionario_id integer not null references public.contas(id),
 estado text not null default 'pendente' check(estado in ('pendente','aceite','rejeitado')),
 requested_at timestamptz not null default now(), reviewed_at timestamptz, reviewed_by integer references public.contas(id),
 unique(empresa_id,funcionario_id)
);
create table if not exists public.eventos (
 id integer generated by default as identity primary key,
 empresa_id integer not null references public.empresas(id), nome_evento text not null, descricao text, zona text not null,
 inicio timestamptz not null, fim timestamptz not null, estado text not null default 'pendente' check(estado in ('pendente','em_curso','concluido','cancelado')),
 criado_por integer not null references public.contas(id), created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 constraint eventos_datas_validas check(fim>inicio)
);
create table if not exists public.evento_funcionarios (
 id integer generated by default as identity primary key,
 evento_id integer not null references public.eventos(id), funcionario_id integer not null references public.contas(id),
 funcao text, materiais text, resposta text not null default 'pendente' check(resposta in ('pendente','aceite','rejeitado')),
 motivo_rejeicao text, responded_at timestamptz, estado text not null default 'pendente' check(estado in ('pendente','em_curso','concluido')),
 ativo boolean not null default true, assigned_at timestamptz not null default now(), completed_at timestamptz, removed_at timestamptz,
 unique(evento_id,funcionario_id)
);
create table if not exists public.historico_eventos (
 id integer generated by default as identity primary key,
 evento_id integer not null references public.eventos(id), conta_id integer not null references public.contas(id), funcionario_id integer references public.contas(id),
 acao text not null, dados_anteriores jsonb, dados_novos jsonb, created_at timestamptz not null default now()
);
create table if not exists public.notificacoes (
 id integer generated by default as identity primary key,
 funcionario_id integer not null references public.contas(id), empresa_id integer not null references public.empresas(id), evento_id integer references public.eventos(id), evento_funcionario_id integer references public.evento_funcionarios(id),
 titulo text not null, mensagem text not null, tipo text not null check(tipo in ('publicacao','lembrete_09','lembrete_15','lembrete_20','lembrete_2h','alteracao','cancelamento','admissao')),
 agendada_para timestamptz not null default now(), enviada boolean not null default false, lida boolean not null default false, cancelada boolean not null default false, enviada_em timestamptz, created_at timestamptz not null default now()
);
create table if not exists public.push_subscriptions (
 id integer generated by default as identity primary key, conta_id integer not null references public.contas(id), endpoint text not null unique,
 p256dh text not null, auth text not null, dispositivo text, ativo boolean not null default true, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists idx_memberships_employee on public.empresa_funcionarios(funcionario_id,estado);
create index if not exists idx_events_company_start on public.eventos(empresa_id,inicio);
create index if not exists idx_assignments_employee on public.evento_funcionarios(funcionario_id,ativo);
create index if not exists idx_notifications_due on public.notificacoes(enviada,cancelada,agendada_para);
create index if not exists idx_history_event on public.historico_eventos(evento_id,created_at desc);
-- RLS está ativo em todas as tabelas. A aplicação acede pelo backend com service_role,
-- que ignora RLS; por isso cada Route Handler valida sessão, papel e associação antes de cada operação.
-- Não conceder acesso direto às tabelas ao papel anon/authenticated.
do $$ declare t text; begin foreach t in array array['contas','empresas','empresa_gerentes','empresa_funcionarios','eventos','evento_funcionarios','historico_eventos','notificacoes','push_subscriptions'] loop execute format('alter table public.%I enable row level security',t); execute format('revoke all on public.%I from anon, authenticated',t); end loop; end $$;
-- Políticas explícitas deny-all para clientes diretos. O backend privilegiado executa as operações autorizadas.
do $$ declare t text; begin foreach t in array array['contas','empresas','empresa_gerentes','empresa_funcionarios','eventos','evento_funcionarios','historico_eventos','notificacoes','push_subscriptions'] loop execute format('drop policy if exists deny_client_access on public.%I',t); execute format('create policy deny_client_access on public.%I for all to anon, authenticated using (false) with check (false)',t); end loop; end $$;
create unique index if not exists idx_contas_username_lower on public.contas (lower(username));
